// Generate ts/index.ts from jsonschema/dermiai.schema.json (itself generated from Pydantic).
// Run via `just schemas`, which exports the JSON Schema first.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import prettier from "prettier";

const schemaPath = fileURLToPath(new URL("../jsonschema/dermiai.schema.json", import.meta.url));
const outPath = fileURLToPath(new URL("../ts/index.ts", import.meta.url));

const schema = JSON.parse(await readFile(schemaPath, "utf8"));

// Pydantic gives every field a `title`, which json-schema-to-typescript turns into an exported
// alias per field (Type1, Content2, ...). Keep titles only on $defs, so only contract types get names.
function stripPropertyTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripPropertyTitles);
  if (node === null || typeof node !== "object") return;
  for (const prop of Object.values(node.properties ?? {})) delete prop.title;
  Object.values(node).forEach(stripPropertyTitles);
}
stripPropertyTitles(schema);

const banner = `/**
 * GENERATED by packages/schemas/scripts/gen-ts.mjs from the Pydantic models in
 * packages/schemas/src/dermiai_schemas. DO NOT EDIT. Run \`just schemas\` instead.
 */`;

const ts = await compile(schema, "DermiAIContracts", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
});

const config = (await prettier.resolveConfig(outPath)) ?? {};
const formatted = await prettier.format(ts, { ...config, parser: "typescript" });
await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, formatted.replace(/\r\n/g, "\n"));
console.log(`wrote ${outPath}`);
